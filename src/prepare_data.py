"""Phase 2 Data Preparation (docs/plan.md §4).

Builds the fixed Jigsaw train/val split, the Civil Comments augmentation pool and the
E0/E1/E2 training sets, then writes parquet files and data_summary.md to data/processed/.

Run: .venv/Scripts/python src/prepare_data.py
"""
import subprocess
import sys
from importlib.metadata import version

import numpy as np
import pandas as pd
from iterstrat.ml_stratifiers import MultilabelStratifiedShuffleSplit

from common import CIVIL_TO_JIGSAW, HARD_THRESHOLD, LABELS, PROCESSED, RAW, ROOT, SEED, clean

CIVIL_EVAL_LABELS = [l for l in LABELS if l != "severe_toxic"]  # Civil test has no severe_toxicity positives
# EDA reference values (eda_results.md), only printed next to the computed numbers as a sanity check.
# The split sizes are approximate there (≈); iterstrat takes ceil(0.1 * n) for val, so ±1 is expected.
EDA_REF = {
    "Jigsaw train (raw)": "159,571",
    "Jigsaw dedup removed": "0",
    "Jigsaw train split": "≈143,614",
    "Jigsaw val split": "≈15,957",
    "Jigsaw labeled test": "63,978",
    "Civil test (before exclusion)": "97,320",
}
# Overlap with Civil train, distinct texts. EDA measured Jigsaw train before the split (val + train split).
EDA_OVERLAP = {
    "Civil test": "1,217",
    "Jigsaw val split": "38 (val + train split combined)",
    "Jigsaw labeled test": "24",
    "Jigsaw train split": "38 (val + train split combined)",
}
PACKAGES = ["iterative-stratification", "numpy", "pandas", "pyarrow", "scikit-learn"]

md = ["# Data summary", "", "Generated by `src/prepare_data.py`; do not edit by hand.", ""]


def table(header, rows):
    md.append("| " + " | ".join(header) + " |")
    md.append("|" + "---|" * len(header))
    md.extend("| " + " | ".join(str(c) for c in r) + " |" for r in rows)
    md.append("")


def load_civil(split):
    df = pd.read_csv(RAW / "civil_comments" / f"{split}.csv", usecols=["text", *CIVIL_TO_JIGSAW])
    return df.rename(columns=CIVIL_TO_JIGSAW)


def as_float32(df):
    return df.astype({l: "float32" for l in LABELS if l in df})


def git_commit():
    """HEAD hash, suffixed -dirty when tracked files have uncommitted changes."""
    git = lambda *a: subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    head = git("rev-parse", "HEAD") or "unknown"
    return head + ("-dirty" if git("status", "--porcelain", "--untracked-files=no") else "")


# ---------- Step 1-2: load and clean ----------
jig = pd.read_csv(RAW / "jigsaw" / "train.csv", usecols=["comment_text", *LABELS]).rename(columns={"comment_text": "text"})
jt = pd.read_csv(RAW / "jigsaw" / "test.csv").merge(pd.read_csv(RAW / "jigsaw" / "test_labels.csv"), on="id")
jt = jt[(jt[LABELS] != -1).all(axis=1)].rename(columns={"comment_text": "text"})[["id", "text", *LABELS]]
civ = load_civil("train")
civ_test = load_civil("test")
for df in (jig, jt, civ, civ_test):
    df["text"] = clean(df["text"])

# ---------- Step 3: dedup Jigsaw train, multi-label stratified split ----------
n_raw = len(jig)
jig = jig.drop_duplicates("text").reset_index(drop=True)
msss = MultilabelStratifiedShuffleSplit(n_splits=1, test_size=0.1, random_state=SEED)
tr_idx, va_idx = next(msss.split(jig["text"], jig[LABELS].to_numpy()))
train = as_float32(jig.iloc[np.sort(tr_idx)].reset_index(drop=True))
val = as_float32(jig.iloc[np.sort(va_idx)].reset_index(drop=True))
n = len(train)

# ---------- Step 4: Civil augmentation pool (from Civil train only) ----------
n_civ = len(civ)
pool = civ.dropna(subset=["text"])
n_null = n_civ - len(pool)
overlap_rows, excluded = [], pd.Series(False, index=pool.index)
for name, other, exclude in [("Civil test", civ_test["text"], True), ("Jigsaw val split", val["text"], True),
                             ("Jigsaw labeled test", jt["text"], True), ("Jigsaw train split", train["text"], False)]:
    hit = pool["text"].isin(set(other))
    if exclude:
        excluded |= hit
    overlap_rows.append([f"Civil train ∩ {name}", f"{pool.loc[hit, 'text'].nunique():,}", f"{int(hit.sum()):,}",
                         EDA_OVERLAP[name], "excluded" if exclude else "kept (both are training data)"])
pool = pool[~excluded]
# One seeded permutation; taking a prefix gives nested samples for the ratio ablation (plan §7).
pool = as_float32(pool.sample(frac=1, random_state=SEED).reset_index(drop=True))
assert len(pool) >= 2 * n, "pool too small for the 2:1 ablation"

# ---------- Step 7: Civil test; drop rows whose text also appears in Jigsaw train (incl. val) ----------
in_jig = civ_test["text"].isin(set(jig["text"]))
civ_test_overlap = [f"{civ_test.loc[in_jig, 'text'].nunique():,}", f"{int(in_jig.sum()):,}"]
civ_test = civ_test[~in_jig].reset_index(drop=True)
assert (civ_test["severe_toxic"] >= HARD_THRESHOLD).sum() == 0, "Civil test now has severe_toxicity positives"
test_civil = civ_test[["text"]].assign(**{l: (civ_test[l] >= HARD_THRESHOLD).astype("float32") for l in CIVIL_EVAL_LABELS})

# ---------- Step 5-6: 1:1 sample, E0/E1/E2 ----------
ext = pool.iloc[:n]
train_e0 = train.assign(source="jigsaw")
combined = pd.concat([train_e0, ext.assign(source="civil")], ignore_index=True)
train_e2 = combined.sample(frac=1, random_state=SEED).reset_index(drop=True)  # soft: raw 0-1 scores
train_e1 = train_e2.copy()
train_e1[LABELS] = (train_e2[LABELS] >= HARD_THRESHOLD).astype("float32")  # Jigsaw rows are 0/1, unchanged

# ---------- Write ----------
PROCESSED.mkdir(parents=True, exist_ok=True)
outputs = {"train_e0": train_e0, "train_e1": train_e1, "train_e2": train_e2, "val": val,
           "test_jigsaw": as_float32(jt.reset_index(drop=True)), "test_civil": test_civil, "civil_pool_perm": pool}

# ---------- Acceptance checks (plan §4.3) ----------
eval_texts = set(val["text"]) | set(outputs["test_jigsaw"]["text"]) | set(test_civil["text"])
for k in ("train_e0", "train_e1", "train_e2", "civil_pool_perm"):  # whole pool: ablation prefixes go up to 2n
    assert not set(outputs[k]["text"]) & eval_texts, f"{k} overlaps val/test"
assert train_e1["text"].equals(train_e2["text"]), "E1 and E2 differ in text or row order"
assert (train_e2["source"] == "civil").sum() == n, "external sample size != len(jigsaw_train_split)"
for k, df in outputs.items():
    assert all(df[l].dtype == "float32" for l in LABELS if l in df), f"{k} labels are not float32"
ext1, ext2 = train_e1[train_e1["source"] == "civil"], train_e2[train_e2["source"] == "civil"]
assert ext1[LABELS].isin([0.0, 1.0]).all().all(), "E1 external labels not in {0, 1}"
assert ext2[LABELS].ge(0).all().all() and ext2[LABELS].le(1).all().all(), "E2 external labels outside [0, 1]"
key = ["text", *LABELS]
jig_parts = [df.loc[df["source"] == "jigsaw", key].sort_values(key).reset_index(drop=True)
             for df in (train_e0, train_e1, train_e2)]
assert jig_parts[0].equals(jig_parts[1]) and jig_parts[0].equals(jig_parts[2]), "Jigsaw part differs across E0/E1/E2"

for k, df in outputs.items():
    df.to_parquet(PROCESSED / f"{k}.parquet", index=False)

# ---------- data_summary.md ----------
md += ["## Row counts", ""]
table(["File", "Rows", "EDA reference"],
      [["Jigsaw train (raw)", f"{n_raw:,}", EDA_REF["Jigsaw train (raw)"]],
       ["Jigsaw train after dedup", f"{len(jig):,} ({n_raw - len(jig)} removed)",
        f"{EDA_REF['Jigsaw dedup removed']} removed"],
       ["train_e0 (Jigsaw train split)", f"{n:,}", EDA_REF["Jigsaw train split"]],
       ["val (Jigsaw val split)", f"{len(val):,}", EDA_REF["Jigsaw val split"]],
       ["train_e1 / train_e2", f"{len(train_e1):,} ({n:,} Jigsaw + {n:,} Civil)", "—"],
       ["test_jigsaw (official labeled test)", f"{len(jt):,}", EDA_REF["Jigsaw labeled test"]],
       ["test_civil", f"{len(test_civil):,}", f"{EDA_REF['Civil test (before exclusion)']} before exclusion"],
       ["civil_pool_perm (augmentation pool)", f"{len(pool):,}", "—"]])
md += ["- EDA split sizes are approximate (≈). `MultilabelStratifiedShuffleSplit` takes ceil(0.1 × n) rows for val, "
       "so a ±1 difference is expected, not an error.", ""]

md += ["## Civil augmentation pool", "",
       f"- Civil train rows: {n_civ:,}; null text removed: {n_null:,}",
       f"- Rows excluded for overlap: {int(excluded.sum()):,}; pool size: {len(pool):,}",
       "- The pool is not de-duplicated internally.", ""]
table(["Overlap (exact text after strip)", "Distinct texts", "Rows in Civil train", "EDA reference (texts)", "Action"],
      overlap_rows)
md += [f"- Civil test ∩ Jigsaw train (incl. val): {civ_test_overlap[0]} distinct texts, {civ_test_overlap[1]} rows "
       "removed from test_civil.", ""]

md += ["## Label positives", "",
       "Hard counts use label = 1 (score ≥ 0.5 for Civil). E2 soft mass = sum of label values.", ""]
table(["Label", "train_e0", "val", "train_e1", "train_e2 soft mass", "test_jigsaw", "test_civil"],
      [[l, f"{int(train_e0[l].sum()):,}", f"{int(val[l].sum()):,}", f"{int(train_e1[l].sum()):,}",
        f"{train_e2[l].sum():,.0f}", f"{int(outputs['test_jigsaw'][l].sum()):,}",
        f"{int(test_civil[l].sum()):,}" if l in test_civil else "—"] for l in LABELS])

md += ["## Jigsaw train vs. val label ratio", ""]
table(["Label", "train %", "val %", "Diff (pp)"],
      [[l, f"{train[l].mean():.3%}", f"{val[l].mean():.3%}", f"{(val[l].mean() - train[l].mean()) * 100:+.3f}"]
       for l in LABELS])

md += ["## Acceptance checks", "", "All plan §4.3 assertions passed.", "",
       "## Environment", "",
       f"- Git commit: `{git_commit()}`",
       f"- Python {sys.version.split()[0]}",
       "- " + ", ".join(f"{p}=={version(p)}" for p in PACKAGES), ""]
(PROCESSED / "data_summary.md").write_text("\n".join(md), encoding="utf-8")
sys.stdout.reconfigure(encoding="utf-8")  # summary contains ∩ / ≥, which the Windows console codepage can't encode
print("\n".join(md))
print(f"Wrote {len(outputs)} parquet files and data_summary.md to {PROCESSED}")
